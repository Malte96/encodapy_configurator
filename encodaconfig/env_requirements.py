"""
Environment variable introspection for the encodaconfig tool.

Reuses the pydantic-settings models of `encodapy.config.env_values` to
show which environment variables are required for the interfaces used in
the current configuration and to generate a `.env` template.
"""

from typing import Any

from encodapy.config.env_values import (
    BasicEnvVariables,
    FileEnvVariables,
    FiwareEnvVariables,
    MQTTEnvVariables,
)


def _fields(settings_class, prefix: str) -> list[dict[str, Any]]:
    """Extract field metadata from a pydantic-settings class.

    Args:
        settings_class: The settings class to inspect.
        prefix (str): The env prefix of the settings class.

    Returns:
        List[Dict[str, Any]]: One entry per field with name (incl.
        prefix), default, description and required flag.
    """
    fields = []
    for name, field in settings_class.model_fields.items():
        required = field.is_required()
        default = "" if required or field.default is None else str(field.default)
        fields.append(
            {
                "name": f"{prefix}{name.upper()}",
                "default": default,
                "description": field.description or "",
                "required": required,
            }
        )
    return fields


def get_env_requirements(
    interfaces: dict[str, bool],
) -> dict[str, list[dict[str, Any]]]:
    """Get the environment variable requirements for the used interfaces.

    Args:
        interfaces (Dict[str, bool]): The interfaces section of the
            configuration (mqtt/fiware/file with boolean values).

    Returns:
        Dict[str, List[Dict[str, Any]]]: Mapping of group name
        ("basic" + one per active interface) to its field list.
    """
    groups: dict[str, list[dict[str, Any]]] = {
        "basic (always required)": _fields(BasicEnvVariables, "")
    }
    if interfaces.get("fiware"):
        groups["fiware (FIWARE_ prefix)"] = _fields(FiwareEnvVariables, "FIWARE_")
    if interfaces.get("mqtt"):
        groups["mqtt (MQTT_ prefix)"] = _fields(MQTTEnvVariables, "MQTT_")
    if interfaces.get("file"):
        groups["file (FILE_ prefix)"] = _fields(FileEnvVariables, "FILE_")
    return groups


def generate_env_template(interfaces: dict[str, bool]) -> str:
    """Generate a `.env` file template for the used interfaces.

    Only required variables (without default) are uncommented; optional
    variables are listed as comments for orientation.

    Args:
        interfaces (Dict[str, bool]): The interfaces section of the
            configuration.

    Returns:
        str: The `.env` template content.
    """
    lines = [
        "# .env template generated by encodaconfig",
        "# Only variables without a default value must be set;",
        "# optional variables are listed as comments with their defaults.",
        "",
    ]
    for group, fields in get_env_requirements(interfaces).items():
        lines.append(f"# --- {group} ---")
        for field in fields:
            if field["required"]:
                lines.append(f"{field['name']}=")
            else:
                default = field["default"] or ""
                lines.append(f"# {field['name']}={default}")
        lines.append("")
    return "\n".join(lines)


__all__ = ["generate_env_template", "get_env_requirements"]
